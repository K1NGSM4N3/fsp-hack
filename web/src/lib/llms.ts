const pageLine = (p: PublicPage) => `- [${p.name}](${absoluteUrl(p.path)}): ${p.description} Для кого: ${p.audience}.`;

export function llmsTxt(): string {
  const { privacy, ...pages } = PUBLIC_PAGES;
  return [
    `# ${SITE_NAME}`,
    "",
    `> ${SUMMARY}`,
    "",
    "Главное:",
    ...KEY_FACTS.map((f) => `- ${f}`),
    "",
    "## Страницы",
    ...Object.values(pages).map(pageLine),
    "",
    "## Документы",
    pageLine(privacy),
    "",
    "## Optional",
    `- [Полный текст сайта и подробности механики](${absoluteUrl("/llms-full.txt")}): тест, подбор, приватность, ФСП, ATS, защита от фиктивных вакансий, результаты валидации`,
    `- [Карта сайта](${absoluteUrl("/sitemap.xml")}): все публичные страницы и опубликованные вакансии`,
    "",
  ].join("\n");
}

export function vacancyLine(v: PublicVacancy): string {
  const place = [WORK_FORMAT_LABEL[v.work_format], v.city ?? v.company_city].filter(Boolean).join(", ");
  return `- [${v.title}](${absoluteUrl(`/vacancies/${v.id}`)}) — ${v.company_name}; ${SPEC_LONG_LABEL[v.specialization]} · ${GRADE_LABEL[v.grade]}; ${formatSalaryRange(v.salary.min, v.salary.max)} в месяц; ${place}`;
}

export function llmsFullTxt(pages: { page: PublicPage; text: string | null }[], vacancies: PublicVacancy[], at: Date): string {
  return [
    `# ${SITE_NAME} — полный текст`,
    "",
    `> ${SUMMARY}`,
    "",
    `Состав: описание продукта, текст публичных страниц сайта ${absoluteUrl("/")} и список опубликованных вакансий. Собрано ${at.toISOString().slice(0, 10)}.`,
    "",
    "## О продукте",
    ...FACTS.flatMap((s) => ["", `### ${s.title}`, ...s.items.map((i) => `- ${i}`)]),
    "",
    ...pages.flatMap(({ page, text }) => ["", `## ${page.name} — ${absoluteUrl(page.path)}`, "", `> ${page.description}`, "", text ?? "Текст страницы временно недоступен.", ""]),
    ...(vacancies.length ? ["", "## Опубликованные вакансии", "", ...vacancies.map(vacancyLine), ""] : []),
  ]
    .join("\n")
    .replace(/\n{3,}/g, "\n\n");
}
