macro_rules! entry {
    (
        stems: [$($stem:literal),+ $(,)?],
        $(code: ($lang:literal, $src:literal),)?
        correct: [$($correct:literal),+ $(,)?],
        distractors: [$($distractor:literal),+ $(,)?] $(,)?
    ) => {
        Entry {
            stems: &[$($stem),+],
            code: entry!(@code $(($lang, $src))?),
            correct: &[$($correct),+],
            distractors: &[$($distractor),+],
        }
    };
    (@code ($lang:literal, $src:literal)) => { Some(($lang, $src)) };
    (@code) => { None };
}

