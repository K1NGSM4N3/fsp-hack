fn kmeans_assign(points: &[i64], centroids: &[f64]) -> Option<Vec<usize>> {
    points
        .iter()
        .map(|p| {
            let d: Vec<f64> = centroids.iter().map(|c| (*p as f64 - c).abs()).collect();
            if (d[0] - d[1]).abs() < 1e-9 {
                None
            } else if d[0] < d[1] {
                Some(0)
            } else {
                Some(1)
            }
        })
        .collect()
}

fn kmeans_update(points: &[i64], labels: &[usize]) -> Option<Vec<f64>> {
    (0..2)
        .map(|k| {
            let members: Vec<i64> = points
                .iter()
                .zip(labels)
                .filter(|(_, l)| **l == k)
                .map(|(p, _)| *p)
                .collect();
            (!members.is_empty()).then(|| members.iter().sum::<i64>() as f64 / members.len() as f64)
        })
        .collect()
}

fn kmeans(level: u8, rng: &mut Rng) -> Draft {
    for _ in 0..128 {
        let n = range(rng, 6, 9) as usize;
        let mut points: Vec<i64> = (0..n).map(|_| range(rng, 0, 40)).collect();
        points.sort_unstable();
        points.dedup();
        if points.len() < 5 {
            continue;
        }
        let points = shuffled(rng, points);
        let c1 = range(rng, 0, 20);
        let c2 = c1 + range(rng, 3, 20);
        let init = [c1 as f64, c2 as f64];
        let Some(labels) = kmeans_assign(&points, &init) else {
            continue;
        };
        let Some(next) = kmeans_update(&points, &labels) else {
            continue;
        };
        let list = join(&points, ", ");
        let intro = format!(
            "Одномерные точки: {list}. Алгоритм k-means с k = 2, начальные центроиды: c₁ = {c1}, c₂ = {c2}. Расстояние — модуль разности."
        );
        return match level {
            1 => Draft::integer(
                format!(
                    "{intro} Сколько точек будет отнесено к кластеру c₁ на первом шаге назначения?"
                ),
                labels.iter().filter(|l| **l == 0).count() as i64,
            ),
            2 => rounded(
                format!(
                    "{intro} Чему станет равен центроид c₁ после первой итерации (назначение точек и пересчёт центроидов)?"
                ),
                next[0],
                2,
            ),
            _ => {
                let Some(labels2) = kmeans_assign(&points, &next) else {
                    continue;
                };
                let Some(after) = kmeans_update(&points, &labels2) else {
                    continue;
                };
                if labels2 == labels {
                    continue;
                }
                rounded(
                    format!(
                        "{intro} Чему будет равен центроид c₂ после второй итерации (два раза: назначение точек и пересчёт центроидов)?"
                    ),
                    after[1],
                    2,
                )
            }
        };
    }
    Draft::integer(
        "Точки 1, 2, 10, 11; k = 2, центроиды 0 и 12. Сколько точек попадёт к первому центроиду?",
        2,
    )
}

/// Nonzero multiple of 0.1 with magnitude up to `max_tenths / 10`.
fn signed_tenths(rng: &mut Rng, max_tenths: i64, negative: f64) -> f64 {
    let sign = if chance(rng, negative) { -1.0 } else { 1.0 };
    sign * range(rng, 1, max_tenths) as f64 / 10.0
}

fn gradient_step(level: u8, rng: &mut Rng) -> Draft {
    let loss = *pick(rng, &["L", "J"]);
    if level == 1 {
        let lr: f64 = *pick(rng, &[0.01, 0.02, 0.03, 0.05, 0.1, 0.2]);
        let w = signed_tenths(rng, 25, 0.25);
        let grad = signed_tenths(rng, 60, 0.5);
        let p = *pick(rng, &["w", "θ", "w₁", "w₂", "w₃", "β"]);
        let (w_s, g, lr_s) = (fmt_number(w), fmt_number(grad), fmt_number(lr));
        let prompt = match range(rng, 0, 3) {
            0 => format!(
                "Обычный SGD без momentum. Текущее значение веса {p} = {w_s}, градиент функции потерь по нему ∂{loss}/∂{p} = {g}, learning rate = {lr_s}. Каким станет {p} после одного шага?"
            ),
            1 => format!(
                "Параметр {p} обновляется обычным градиентным спуском без momentum и weight decay. Сейчас {p} = {w_s}, ∂{loss}/∂{p} = {g}, learning rate = {lr_s}. Чему будет равен {p} после одного обновления?"
            ),
            2 => format!(
                "Оптимизатор — SGD без momentum, learning rate = {lr_s}. Вес {p} сейчас равен {w_s}, а градиент функции потерь {loss} по этому весу равен {g}. Какое значение примет {p} после одного шага оптимизатора?"
            ),
            _ => format!(
                "Один шаг SGD без momentum: learning rate = {lr_s}, текущий вес {p} = {w_s}, ∂{loss}/∂{p} = {g}. Каким станет {p} после шага?"
            ),
        };
        return rounded(prompt, w - lr * grad, 3);
    }
    let lr: f64 = *pick(rng, &[0.1, 0.05, 0.02, 0.01]);
    let w: f64 = *pick(rng, &[-1.5, -1.0, -0.5, 0.5, 1.0, 1.5, 2.0, 2.5]);
    let b0: f64 = *pick(rng, &[-1.0, -0.5, 0.0, 0.5, 1.0, 1.5]);
    let (wn, bn) = *pick(
        rng,
        &[
            ("w", "b"),
            ("k", "b"),
            ("a", "b"),
            ("θ₁", "θ₀"),
            ("w₁", "w₀"),
        ],
    );
    let n = if level == 2 {
        1
    } else {
        range(rng, 2, 3) as usize
    };
    let samples: Vec<(i64, i64)> = (0..n)
        .map(|_| (range(rng, 1, 5), range(rng, 0, 12)))
        .collect();
    let grad = samples
        .iter()
        .map(|(x, y)| 2.0 * (w * *x as f64 + b0 - *y as f64) * *x as f64)
        .sum::<f64>()
        / n as f64;
    let data = samples
        .iter()
        .map(|(x, y)| format!("(x = {x}, y = {y})"))
        .collect::<Vec<_>>()
        .join(", ");
    let loss = if n == 1 {
        format!("{loss} = (ŷ − y)²")
    } else {
        format!("{loss} = (1/N)·Σ(ŷᵢ − yᵢ)² — среднее по батчу")
    };
    let (w_s, b_s, lr_s) = (fmt_number(w), fmt_number(b0), fmt_number(lr));
    let prompt = match range(rng, 0, 2) {
        0 => format!(
            "Линейная модель ŷ = {wn}·x + {bn}, сейчас {wn} = {w_s}, {bn} = {b_s}. Функция потерь {loss}. Данные: {data}. \
             Сделайте один шаг градиентного спуска по {wn} ({bn} не меняется) с learning rate = {lr_s}. Каким станет {wn}?"
        ),
        1 => format!(
            "Модель ŷ = {wn}·x + {bn} с текущими параметрами {wn} = {w_s}, {bn} = {b_s}. Функция потерь {loss}. Обучающие данные: {data}. \
             Выполните один шаг градиентного спуска только по {wn} ({bn} заморожен), learning rate = {lr_s}. Чему будет равен {wn} после шага?"
        ),
        _ => format!(
            "Одномерная линейная регрессия ŷ = {wn}·x + {bn}; сейчас {wn} = {w_s}, {bn} = {b_s}. Функция потерь {loss}. Данные: {data}. \
             Обновите {wn} одним шагом градиентного спуска с learning rate = {lr_s}, а {bn} оставьте прежним. Каким станет {wn}?"
        ),
    };
    rounded(prompt, w - lr * grad, 3)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn percentile_matches_numpy_linear() {
        let x = [1, 2, 3, 4];
        assert!((numpy_percentile(&x, 25.0) - 1.75).abs() < 1e-12);
        assert!((numpy_percentile(&x, 50.0) - 2.5).abs() < 1e-12);
        assert!((numpy_percentile(&[7, 15, 36, 39, 40, 41], 90.0) - 40.5).abs() < 1e-12);
    }

    #[test]
    fn broadcasting_rules() {
        assert_eq!(broadcast(&[3, 1], &[4]), Some(vec![3, 4]));
        assert_eq!(broadcast(&[5, 1, 4], &[3, 1]), Some(vec![5, 3, 4]));
        assert_eq!(broadcast(&[3], &[4]), None);
        assert_eq!(broadcast(&[2, 3], &[3]), Some(vec![2, 3]));
    }

    #[test]
    fn early_stopping_semantics() {
        let val = [0.9, 0.7, 0.75, 0.6, 0.65, 0.66, 0.7];
        assert_eq!(early_stopping(&val, 2), (Some(5), 3));
        assert_eq!(early_stopping(&val, 1), (Some(2), 1));
    }

    #[test]
    fn kmeans_iteration() {
        let points = [1, 2, 10, 11, 12];
        let labels = kmeans_assign(&points, &[0.0, 5.0]).unwrap();
        assert_eq!(labels, vec![0, 0, 1, 1, 1]);
        let next = kmeans_update(&points, &labels).unwrap();
        assert!((next[0] - 1.5).abs() < 1e-12 && (next[1] - 11.0).abs() < 1e-12);
        assert_eq!(kmeans_assign(&points, &[0.0, 2.0]), None);
    }
}
